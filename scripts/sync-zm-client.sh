#!/bin/sh
# Regenerates internal/approvals/web/zm-decisions.js from t3code's
# packages/zm-client/src/decisions.ts: the same logic the Mezze app's Decisions runs,
# with only the TypeScript types stripped (node's stripTypeScriptTypes).
# Never edit the output by hand; change decisions.ts in t3code, then run:
#   scripts/sync-zm-client.sh [t3code checkout, default ~/code/t3code] [ref, default origin/main]
set -eu
repo=${1:-$HOME/code/t3code}
ref=${2:-origin/main}
out=$(dirname "$0")/../internal/approvals/web/zm-decisions.js
commit=$(git -C "$repo" rev-parse "$ref")
git -C "$repo" show "$commit:packages/zm-client/src/decisions.ts" | node -e '
let s = ""; process.stdin.on("data", (d) => (s += d)).on("end", () => {
  const js = require("node:module").stripTypeScriptTypes(s, { mode: "strip" });
  process.stdout.write(js.split("\n").map((l) => l.trimEnd()).join("\n").replace(/\n{3,}/g, "\n\n"));
});' > "$out.body"
sum=$(shasum -a 256 "$out.body" | cut -c1-64)
{
  echo "// GENERATED by scripts/sync-zm-client.sh: do not edit."
  echo "// source: t3code packages/zm-client/src/decisions.ts @ $commit"
  echo "// body-sha256: $sum"
  cat "$out.body"
} > "$out"
rm "$out.body"
echo "wrote $out from $commit"
