package holder

import (
	"sync"

	"github.com/sengirunners/mezze/internal/session/holder/replaymode"
)

// Ring is a fixed-size scrollback buffer addressed by absolute byte offsets:
// offset 0 is the first byte the PTY ever wrote, end is the total written.
// Only the last len(buf) bytes are kept. Readers wait for new bytes on the
// channel returned by Next; Close wakes them for good. The holder keeps one;
// the daemon keeps a mirror at the same offsets (WriteAt).
type Ring struct {
	mu         sync.Mutex
	buf        []byte
	end        int64
	floor      int64 // the oldest offset ever written (a mirror that started late, or after a gap)
	changed    chan struct{}
	closed     bool
	checkpoint replaymode.Parser // exact parser state immediately before start()
	pending    *ReplayCheckpoint // at most one offset-bound next-write checkpoint
}

// NewRing returns an empty ring of size bytes.
func NewRing(size int) *Ring {
	return &Ring{buf: make([]byte, size), changed: make(chan struct{})}
}

// Write appends p, dropping the oldest bytes beyond the buffer size.
func (r *Ring) Write(p []byte) (int, error) {
	r.mu.Lock()
	defer r.mu.Unlock()
	r.pending = nil
	r.append(p)
	return len(p), nil
}

// WriteAt appends p, which starts at absolute offset off: bytes already held
// are skipped, and a gap (off past the end) moves the end and the floor
// forward, so the ring keeps the writer's offsets and never serves the gap.
func (r *Ring) WriteAt(off int64, p []byte) {
	r.mu.Lock()
	defer r.mu.Unlock()
	if r.closed {
		return
	}
	pending := r.pending
	r.pending = nil
	if off > r.end {
		r.end, r.floor = off, off
		r.checkpoint = replaymode.Lost()
	}
	if pending != nil && pending.From == off && r.start() == off && r.end == off {
		r.checkpoint = pending.State
	}
	if off+int64(len(p)) <= r.end {
		return
	}
	if off < r.end {
		p = p[r.end-off:]
	}
	r.append(p)
}

func (r *Ring) append(p []byte) {
	if r.closed || len(p) == 0 {
		return
	}
	size := int64(len(r.buf))
	// Advance the floor parser BEFORE overwriting evicted bytes. Large writes
	// also evict their own leading prefix, which must be consumed once.
	nextStart := max(r.floor, r.end+int64(len(p))-size)
	if nextStart > r.start() {
		stop := min(nextStart, r.end)
		if stop > r.start() {
			r.feedHeld(&r.checkpoint, r.start(), stop)
		}
		if nextStart > r.end {
			r.checkpoint.Feed(p[:nextStart-r.end])
		}
	}
	if int64(len(p)) > size {
		r.end += int64(len(p)) - size
		p = p[int64(len(p))-size:]
	}
	pos := r.end % size
	c := copy(r.buf[pos:], p)
	copy(r.buf, p[c:])
	r.end += int64(len(p))
	close(r.changed)
	r.changed = make(chan struct{})
}

// start is the oldest offset still held. Callers hold mu.
func (r *Ring) start() int64 { return max(r.floor, r.end-int64(len(r.buf))) }

// Bounds returns the oldest held offset and the end offset.
func (r *Ring) Bounds() (start, end int64) {
	r.mu.Lock()
	defer r.mu.Unlock()
	return r.start(), r.end
}

// Next copies up to limit bytes from off (clamped to what is held) and
// returns them with their offsets. When nothing is new, wait is closed on the
// next write or Close; closed reports the ring will never grow again.
func (r *Ring) Next(off int64, limit int) (data []byte, from, to int64, wait <-chan struct{}, closed bool) {
	r.mu.Lock()
	defer r.mu.Unlock()
	from = min(max(off, r.start()), r.end)
	n := min(r.end-from, int64(limit))
	data = make([]byte, n)
	if n > 0 {
		size := int64(len(r.buf))
		pos := from % size
		c := copy(data, r.buf[pos:min(pos+n, size)])
		copy(data[c:], r.buf)
	}
	return data, from, from + n, r.changed, r.closed
}

// ReplayCheckpoint binds exact bounded parser state to a raw output offset.
type ReplayCheckpoint struct {
	From  int64
	State replaymode.Parser
}

// ReplayChunk is an atomic snapshot. State is immediately before Data[0],
// including any incomplete control/UTF-8 prefix. No generated bytes are added.
type ReplayChunk struct {
	Data          []byte
	From, To      int64
	State         replaymode.Parser
	Wait          <-chan struct{}
	Closed        bool
	HasCheckpoint bool
}

// NextReplay copies the retained prefix and data under lock, then derives state
// outside the lock. Both copies are bounded by ring capacity; no I/O is locked.
func (r *Ring) NextReplay(off int64, limit int) ReplayChunk { return r.nextReplay(off, limit, true) }
func (r *Ring) nextReplay(off int64, limit int, force bool) ReplayChunk {
	r.mu.Lock()
	from := min(max(off, r.start()), r.end)
	state := r.checkpoint
	hasCheckpoint := force || from != off
	var prefix []byte
	if hasCheckpoint {
		prefix = r.copyHeld(r.start(), from)
	}
	to := from + min(r.end-from, int64(max(0, limit)))
	data := r.copyHeld(from, to)
	wait, closed := r.changed, r.closed
	r.mu.Unlock()
	state.Feed(prefix)
	return ReplayChunk{Data: data, From: from, To: to, State: state, Wait: wait, Closed: closed, HasCheckpoint: hasCheckpoint}
}

// CheckpointNextWrite stages metadata without changing bytes or offsets. It
// applies only to a matching WriteAt on an empty/gapped range. Historical or
// duplicate writes cannot replace an existing retained prefix's checkpoint.
func (r *Ring) CheckpointNextWrite(c ReplayCheckpoint) bool {
	r.mu.Lock()
	defer r.mu.Unlock()
	if r.closed || c.From < r.end || c.From < 0 || (c.From == r.end && r.start() != r.end) {
		return false
	}
	r.pending = &c
	return true
}

// copyHeld copies a range already clamped by its caller; r.mu is held.
func (r *Ring) copyHeld(from, to int64) []byte {
	b := make([]byte, to-from)
	if len(b) > 0 {
		size := int64(len(r.buf))
		pos := from % size
		c := copy(b, r.buf[pos:min(pos+to-from, size)])
		copy(b[c:], r.buf)
	}
	return b
}

// feedHeld consumes wrapped, soon-to-be-evicted bytes without allocating.
func (r *Ring) feedHeld(p *replaymode.Parser, from, to int64) {
	size := int64(len(r.buf))
	pos := from % size
	n := min(to-from, size-pos)
	p.Feed(r.buf[pos : pos+n])
	if n < to-from {
		p.Feed(r.buf[:to-from-n])
	}
}

// Close marks the ring finished and wakes every waiter.
func (r *Ring) Close() {
	r.mu.Lock()
	defer r.mu.Unlock()
	if !r.closed {
		r.closed = true
		close(r.changed)
	}
}
